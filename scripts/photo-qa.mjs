import { chromium } from 'playwright';
import fs from 'node:fs';
fs.mkdirSync('visual-qa', {recursive:true});
const browser=await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:5173/',{waitUntil:'domcontentloaded',timeout:60000});
const photo=page.locator('.photo-stage img');
await photo.waitFor();
await page.waitForFunction(()=>{const im=document.querySelector('.photo-stage img');return im?.complete&&im?.naturalWidth>0},{timeout:45000});
console.log('REFERENCE PHOTO',await photo.evaluate(e=>({width:e.naturalWidth,height:e.naturalHeight,src:e.currentSrc})));
await page.screenshot({path:'visual-qa/photographic-entry.png',timeout:30000});
await page.getByRole('button',{name:/ENTER THE PHOTOGRAPH/}).click();
await page.waitForTimeout(350);
await page.screenshot({path:'visual-qa/photographic-exploration.png',timeout:30000});
await page.locator('.photo-marker').first().click();
if(!await page.locator('[role="dialog"]').isVisible())throw new Error('Portfolio detail panel did not open');
await page.getByRole('button',{name:'Close'}).click();
await page.getByRole('button',{name:/Free Walk/}).click();
await page.locator('canvas').first().waitFor({timeout:30000});
console.log('FREE WALK CANVAS READY',true);
console.log('JS ERRORS',JSON.stringify(errors.slice(0,8)));
await browser.close();
if(errors.some(e=>/Uncaught|TypeError|ReferenceError|SyntaxError/.test(e)))process.exitCode=1;
